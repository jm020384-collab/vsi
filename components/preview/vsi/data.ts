/**
 * Простір фахівця: кураторський контент або дефолт.
 *
 * Для фахівців із реальним фото (`t.photo`) НІКОЛИ не вигадуємо
 * текст від першої особи, якщо його немає в SPACES, — повертаємо
 * порожній масив, і сторінка показує чесний плейсхолдер. Для
 * ілюстрованих демо-персон (без фото) дефолт лишається згенерованим
 * стриманим текстом — уся їхня «особистість» так чи інакше вигадана.
 */
export function specialistSpace(t: Therapist): SpecialistSpace {
  const curated = SPACES[t.id] ?? {};
  const isReal = t.isReal ?? !!t.photo;

  return {
    position:
      curated.position ??
      (isReal
        ? []
        : [
            `У своїй роботі я спираюся на напрям «${t.approach}»: не техніки й поради, а тривале дослідження того, як улаштований ваш внутрішній світ і що в ньому просить уваги.`,
            "Терапія для мене — це передусім стосунок, у якому можна не поспішати, не редагувати себе і поступово повертати собі те, що було відкинуте.",
          ]),
    practice:
      curated.practice ??
      (isReal
        ? []
        : [
            `Формат роботи: ${FORMAT_LABEL[t.format].toLowerCase()}${t.city ? `, ${t.city}` : ""}. Регулярні зустрічі ${t.sessionMinutes} хвилин, зазвичай раз на тиждень. Перші зустрічі — взаємне знайомство без зобов'язань продовжувати.`,
          ]),
    path:
      curated.path ??
      (isReal
        ? []
        : [
            {
              period: `${new Date().getFullYear() - t.yearsOfPractice}`,
              text: "Початок клінічної практики",
            },
            {
              period: "далі",
              text: `${t.status}. Регулярна супервізія і власний аналіз — постійна частина професії.`,
            },
          ]),
    research: curated.research ?? (isReal ? [] : t.topics.slice(0, 3)),
    diplomas: curated.diplomas ?? [],
  };
}

/** Знайти тему або підтему за slug; для підтеми повертається й батьківська. */
export function findTheme(
  slug: string,
): { entry: ThemeEntry; parent?: Theme; subthemes?: ThemeEntry[] } | null {
  for (const theme of THEMES) {
    if (theme.slug === slug) return { entry: theme, subthemes: theme.subthemes };
    const sub = theme.subthemes.find((s) => s.slug === slug);
    if (sub) return { entry: sub, parent: theme };
  }
  return null;
}

/** Увесь контент платформи, що відповідає темі. */
export function themeContent(entry: ThemeEntry) {
  const stems = entry.match.map((s) => s.toLowerCase());
  const hits = (text: string) => {
    const l = text.toLowerCase();
    return stems.some((s) => l.includes(s));
  };

  const therapists = THERAPISTS.filter((t) => hits([...t.topics, t.approach].join(" ")));
  const materials = MATERIALS.filter((m) => hits(`${m.title} ${m.excerpt}`));
  const events = EVENTS.filter((e) => hits(`${e.title} ${e.description}`));

  const articles = materials.filter((m) =>
    ["Стаття", "Розбір", "Словник", "Дослідження"].includes(m.kind),
  );
  const lectures = materials.filter((m) => ["Лекція", "Подкаст"].includes(m.kind));

  return { therapists, materials, articles, lectures, events };
}
