export interface Therapist {
  id: string;
  name: string;
  /** Статус — рівень підготовки в аналітичній традиції. */
  status: string;
  /** Напрям роботи. */
  approach: string;
  yearsOfPractice: number;
  languages: string[];
  format: Format;
  /** Теми, з якими працює. */
  topics: string[];
  priceFrom: number;
  currency: string;
  sessionMinutes: number;
  verified: boolean;
  /** Чи є вільні місця в розкладі. */
  acceptingNew: boolean;
  city?: string;
  /** Шлях до реального фото (public/…). Якщо немає — ілюстрований портрет. */
  photo?: string;
  /** "arch" — фото вирізане за формою арки замість звичайного кадру. */
  portraitStyle?: "arch";
  /** З ким працює. За замовчуванням ["adults"], якщо не вказано. */
  ageGroups?: AgeGroup[];
  /** У якому форматі. За замовчуванням ["individual"], якщо не вказано. */
  workFormats?: WorkFormat[];
  /** Недавно приєднався_лася до VSI — для розділу «Нові у VSI». */
  isNew?: boolean;
  /**
   * Email реального акаунта, який представляє ця демо-персона (якщо є).
   * Коли профіль з таким email отримує статус APPROVED у базі, цей
   * демо-запис виключається з каталогу — щоб людина не подвоювалась.
   */
  realAccountEmail?: string;
  /**
   * Явно позначає запис як реальний профіль з бази (не демо-персону).
   * specialistSpace() орієнтується насамперед на це поле, а не лише на
   * наявність фото — інакше реальна людина без завантаженого фото
   * помилково трактується як демо-персона й отримує вигаданий текст
   * від першої особи.
   */
  isReal?: boolean;
}

